//! Icons8 动图：单尺寸的 1 bit 帧、绘制与全部静态声明。
//!
//! 图形来自 [icons8 动画图标](https://icons8.com/animated-icons/)，与
//! [Wokwi Animator](https://animator.wokwi.com/) 用的是同一份 Lottie 源，按三档边长
//! 栅格化并二值化。`.bin` 在 `assets/icons/animators/`，每帧 `size * size / 8` 字节，
//! 布局与 [`Frame`] 的帧缓冲一致（每字节同列 8 行，低位在上）。
//!
//! 每个动图每个尺寸各是一个静态（`ACTIVITY_32` / `ACTIVITY_48` / `ACTIVITY_64`），由文件
//! 末尾一次 [`crate::anim_icons!`] 声明；只引用其中一档就只多出这一档的字节数。应用也可以
//! 用自己的 `assets/icons/animators/` 再声明一批。

use crate::gfx::Frame;

/// 动图边长档。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum IconSize {
    /// 32 × 32 像素。
    Px32,
    /// 48 × 48 像素。
    Px48,
    /// 64 × 64 像素。
    Px64,
}

impl IconSize {
    /// 三档边长，从小到大。
    pub const ALL: [IconSize; 3] = [IconSize::Px32, IconSize::Px48, IconSize::Px64];

    /// 边长（像素）。
    pub const fn px(self) -> u8 {
        match self {
            IconSize::Px32 => 32,
            IconSize::Px48 => 48,
            IconSize::Px64 => 64,
        }
    }

    /// 单帧字节数：`px * px / 8`。
    pub const fn frame_len(self) -> usize {
        let px = self.px() as usize;
        px * px / 8
    }
}

/// 一个固定尺寸的动图。
pub struct AnimIcon {
    /// 边长档。
    pub size: IconSize,
    /// 帧数据，每帧 [`IconSize::frame_len`] 字节。
    pub frames: &'static [u8],
}

impl AnimIcon {
    /// 帧数。
    pub fn frame_count(&self) -> usize {
        self.frames.len() / self.size.frame_len()
    }
}

/// 在 `(x, y)` 处画动图的第 `index` 帧（对帧数取模）。
///
/// 越界像素与像素外坐标按 [`Frame`] 的裁剪窗口与绘图模式处理；帧数据不满一帧时什么都不画。
pub fn draw_anim_icon(frame: &mut Frame<'_>, x: i16, y: i16, anim: &AnimIcon, index: usize) {
    let size = anim.size.px() as usize;
    let len = anim.size.frame_len();
    let count = anim.frames.len() / len;
    if count == 0 {
        return;
    }
    let base = (index % count) * len;
    let Some(src) = anim.frames.get(base..base + len) else {
        return;
    };
    for page in 0..size / 8 {
        for column in 0..size {
            let bits = src[page * size + column];
            if bits == 0 {
                continue;
            }
            for bit in 0..8 {
                if bits & (1 << bit) != 0 {
                    frame.plot_source(x + column as i16, y + (page * 8 + bit) as i16, true);
                }
            }
        }
    }
}

/// 24 fps 下 `elapsed_ms` 落在第几帧（还没对帧数取模）。
pub fn frame_index(elapsed_ms: u32) -> usize {
    (elapsed_ms as u64 * 24 / 1000) as usize
}

/// 按经过的毫秒数画动图：24 fps 循环播放，`elapsed_ms` 从动画开始时算起。
pub fn draw_anim_icon_at(frame: &mut Frame<'_>, x: i16, y: i16, anim: &AnimIcon, elapsed_ms: u32) {
    draw_anim_icon(frame, x, y, anim, frame_index(elapsed_ms));
}

